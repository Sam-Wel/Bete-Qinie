  and m.related_word_id in (select gz_id from new_en);

-- 2. Add English words that don't exist yet.
insert into public.words (word, language_code)
select distinct n.gloss, 'en'
from new_en n
where not exists (
  select 1 from public.words w where w.language_code = 'en' and btrim(w.word) = n.gloss
);

-- 3. Link each Ge'ez word to its English meanings, both directions, main
-- meaning first (search lists meanings in link order).
create temp table new_pairs on commit drop as
with en as (
  select btrim(word) as word, min(word_id) as word_id
  from public.words where language_code = 'en' group by btrim(word)
)
select n.gz_id, en.word_id as en_id, min(n.ord) as ord
from new_en n join en on en.word = n.gloss
group by n.gz_id, en.word_id;

insert into public.translationmappings (word_id, related_word_id)
select gz_id, en_id from new_pairs order by gz_id, ord;

insert into public.translationmappings (word_id, related_word_id)
select en_id, gz_id from new_pairs order by gz_id, ord;

-- 4. Only links with a Ge'ez word on one side stay.
delete from public.translationmappings m
using public.words a, public.words b
where a.word_id = m.word_id and b.word_id = m.related_word_id
  and a.language_code <> 'gz' and b.language_code <> 'gz';

-- 5. The old English: words no longer linked to anything.
delete from public.words w
where w.language_code = 'en'
  and not exists (select 1 from public.translationmappings m where m.word_id = w.word_id or m.related_word_id = w.word_id);

-- 6. Search in any language, answered as Ge'ez words with their translations.
-- A Ge'ez search finds that word; any other language finds the Ge'ez words it
-- is linked to. Links are read in both directions.
create or replace function public.search_dictionary(search_word text, language text)
returns table (geez_id bigint, geez_word text, target_language text, translated_word text)
language sql
stable
security invoker
set search_path = public
as $fn$
  with hits as (
    select w.word_id from words w
    where w.language_code = search_dictionary.language and btrim(w.word) = btrim(search_dictionary.search_word)
  ), anchors as (
    select h.word_id as gz_id from hits h where search_dictionary.language = 'gz'
    union
    select g.word_id
    from hits h
    join translationmappings m on h.word_id in (m.word_id, m.related_word_id)
    join words g on g.word_id = case when m.word_id = h.word_id then m.related_word_id else m.word_id end
    where g.language_code = 'gz' and search_dictionary.language <> 'gz'
  ), links as (
    select a.gz_id, case when m.word_id = a.gz_id then m.related_word_id else m.word_id end as other_id, m.mapping_id
    from anchors a
    join translationmappings m on a.gz_id in (m.word_id, m.related_word_id)
  ), meanings as (
    select l.gz_id, t.language_code, btrim(t.word) as word, min(l.mapping_id) as first_link
    from links l
    join words t on t.word_id = l.other_id and t.language_code <> 'gz'
    group by l.gz_id, t.language_code, btrim(t.word)
  )
  select g.word_id::bigint, btrim(g.word)::text, mn.language_code::text, mn.word::text
  from anchors a
  join words g on g.word_id = a.gz_id
  left join meanings mn on mn.gz_id = a.gz_id
  order by g.word_id, mn.first_link;
$fn$;

grant execute on function public.search_dictionary(text, text) to anon, authenticated;

