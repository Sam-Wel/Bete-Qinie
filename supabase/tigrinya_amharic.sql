-- Add the words that don't exist yet.
insert into public.words (word, language_code)
select distinct n.word, n.lang from new_tr n
where not exists (select 1 from public.words w where w.language_code = n.lang and btrim(w.word) = n.word);

-- Link them to their Ge'ez word, both directions, main meaning first.
create temp table new_tr_pairs on commit drop as
with w as (
  select language_code, btrim(word) as word, min(word_id) as word_id
  from public.words where language_code in ('ti', 'am') group by language_code, btrim(word)
)
select n.gz_id, w.word_id as tr_id, min(n.ord) as ord, n.lang
from new_tr n join w on w.language_code = n.lang and w.word = n.word
group by n.gz_id, w.word_id, n.lang;

insert into public.translationmappings (word_id, related_word_id)
select gz_id, tr_id from new_tr_pairs order by gz_id, lang, ord;

insert into public.translationmappings (word_id, related_word_id)
select tr_id, gz_id from new_tr_pairs order by gz_id, lang, ord;

